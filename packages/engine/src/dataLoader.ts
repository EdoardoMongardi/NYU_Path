// ============================================================
// Data Loader — Load JSON data files
// ============================================================
//
// loadCourses / loadPrereqs read the bundled course + prereq datasets
// under `packages/engine/src/data/`. loadSchoolConfig reads
// `data/schools/<schoolId>.json` at the repo root with `_meta`
// validation, re-exported from `data/schoolConfigLoader.ts`.
// ============================================================
import type { Course, Prerequisite } from "@nyupath/shared";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = join(__dirname, "data");

export function loadCourses(): Course[] {
    const raw = readFileSync(join(DATA_DIR, "courses.json"), "utf-8");
    return JSON.parse(raw) as Course[];
}

export function loadPrereqs(): Prerequisite[] {
    const raw = readFileSync(join(DATA_DIR, "prereqs.json"), "utf-8");
    return JSON.parse(raw) as Prerequisite[];
}

/**
 * Step 8d PR-2 — bulletin credits for courses OUTSIDE the undergraduate
 * planning catalog (graduate/professional), keyed by courseId. Used solely
 * to resolve an explicit student PIN of an off-catalog course so the solver
 * places it with real credits + a "verify in Albert" caveat instead of
 * dropping it. Generated by tools/bulletin-parser/extractCourses.ts.
 */
export function loadOffCatalogCredits(): Map<string, { title: string; credits: number }> {
    const raw = readFileSync(join(DATA_DIR, "off-catalog-credits.json"), "utf-8");
    const obj = JSON.parse(raw) as Record<string, { title: string; credits: number }>;
    const out = new Map<string, { title: string; credits: number }>();
    for (const [id, v] of Object.entries(obj)) {
        out.set(id, { title: v.title, credits: v.credits });
    }
    return out;
}

